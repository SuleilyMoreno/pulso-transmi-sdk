create table if not exists public.prediction_features (
  feature_id bigint generated by default as identity primary key,
  run_id text not null,
  cycle_id text not null,
  station_id text not null,
  target_at timestamptz not null,
  model_version text not null,
  data_cutoff timestamptz not null,
  features jsonb not null,
  created_at timestamptz not null default now(),
  unique (run_id, station_id, target_at)
);

create index if not exists prediction_features_target_idx
  on public.prediction_features (target_at desc);

alter table public.prediction_features enable row level security;
